export function getToursForLangHe(lang: Lang): Tour[] {
  if (lang !== 'he') return TOURS;
  return TOURS.map((tour) => {
    const ov = HE_TOURS_MAP[tour.slug];
    if (!ov) return tour;
    return {
      ...tour,
      ...ov,
      pricingTiers: tour.pricingTiers.map((tier, idx) => ({
        ...tier,
        label: ov.pricingTierLabels?.[idx] || tier.label,
      })),
      optionalExtras: ov.optionalExtraIds
        ? ov.optionalExtraIds.map((id) => HE_MTIRALA_OPTIONAL_EXTRAS[id])
        : tour.optionalExtras,
    };
  });
}

export function getDestinationsForLangHe(lang: Lang): Destination[] {
  if (lang !== 'he') return DESTINATIONS;
  return DESTINATIONS.map((d) => ({
    ...d,
    ...(HE_DESTINATIONS_MAP[d.slug] || {}),
  }));
}

export function getReviewsForLangHe(lang: Lang): GuestReview[] {
  if (lang !== 'he') return GUEST_REVIEWS;
  return GUEST_REVIEWS.map((r) => ({
    ...r,
    ...(HE_REVIEWS_MAP[r.id] || {}),
  }));
}
