export function getToursForLangUk(lang: Lang): Tour[] {
  if (lang !== 'uk') return TOURS;
  return TOURS.map((tour) => {
    const ov = UK_TOURS_MAP[tour.slug];
    if (!ov) return tour;
    return {
      ...tour,
      ...ov,
      pricingTiers: tour.pricingTiers.map((tier, idx) => ({
        ...tier,
        label: ov.pricingTierLabels?.[idx] || tier.label,
      })),
      optionalExtras: ov.optionalExtraIds
        ? ov.optionalExtraIds.map((id) => UK_MTIRALA_OPTIONAL_EXTRAS[id])
        : tour.optionalExtras,
    };
  });
}

export function getDestinationsForLangUk(lang: Lang): Destination[] {
  if (lang !== 'uk') return DESTINATIONS;
  return DESTINATIONS.map((d) => ({
    ...d,
    ...(UK_DESTINATIONS_MAP[d.slug] || {}),
  }));
}

export function getReviewsForLangUk(lang: Lang): GuestReview[] {
  if (lang !== 'uk') return GUEST_REVIEWS;
  return GUEST_REVIEWS.map((r) => ({
    ...r,
    ...(UK_REVIEWS_MAP[r.id] || {}),
  }));
}
